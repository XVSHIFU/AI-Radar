export type AdminMessage = string | { text: string; params: Record<string, string | number | AdminMessage> };
export function adminMessage(text: string, params: Record<string, string | number | AdminMessage> = {}): AdminMessage { return { text, params }; }
export function at(message: AdminMessage, params: Record<string, string | number> = {}): string {
  if (typeof message !== "string") return at(message.text, Object.fromEntries(Object.entries(message.params).map(([key, value]) => [key, typeof value === "object" ? at(value) : value])));
  if (!Object.hasOwn(messages, message) && !Object.keys(params).length) return message;
  return translate(message, messages[message] ?? message, params);
}
export function adminUsageValue(value: number | null | undefined) { return value == null ? at("未知") : String(value); }
export function adminRecordedUsage(value: number | null | undefined) { return value == null ? at("记录次数未知") : at("已记录 {count} 次", { count: value }); }
